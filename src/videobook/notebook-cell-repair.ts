import type { NotebookCellType } from 'videobook-engine'

export type NotebookCellRepairInput = {
  address: string
  error: string
  mediaLabel: string
  producerAddress: string | null
  provider: string | null
  model: string | null
}

export function notebookCellRepairMediaLabel(type: NotebookCellType): string {
  if (type === 'video' || type === 'generate_video') return 'video'
  if (type === 'image' || type === 'generate_image') return 'image'
  if (type === 'audio' || type === 'generate_audio') return 'audio'
  return 'generation'
}

function generatorLine(provider: string | null, model: string | null): string | null {
  const parts = [provider, model].filter((part): part is string =>
    typeof part === 'string' && part.length > 0)
  return parts.length === 0 ? null : parts.join(' · ')
}

export function notebookCellRepairPrompt(input: NotebookCellRepairInput): string {
  const error = input.error.trim() || 'the provider rejected the request'
  const generator = generatorLine(input.provider, input.model)
  const subject = input.producerAddress
    ? `the ${input.mediaLabel} generated by ${input.producerAddress}`
    : `the ${input.mediaLabel}`
  const settings = input.producerAddress
    ? ` and the settings on ${input.producerAddress}`
    : ' and this cell\'s settings'
  const rerun = input.producerAddress
    ? `re-run ${input.producerAddress} into ${input.address}`
    : `re-run ${input.address}`
  return [
    `Repair ${input.address}: ${subject} failed with "${error}".`,
    generator ? `Generator: ${generator}.` : null,
    `Inspect the recorded provider request${settings}, fix what the provider rejected, and ${rerun} as a preview.`,
  ].filter((line): line is string => line !== null).join(' ')
}
