import { modelSlug } from "@apicity/cost";
import type { Engine } from "videobook-engine";
import { z, type ZodRawShape } from "zod";
import { queue } from "../queue.js";
import { findVideoFile } from "videobook-engine";
import type { SchemaArgs, ToolDef } from "./tool-def.js";
import { requireArtifactKind } from "./_shared.js";
import { derivedLabel } from "../artifact-label.js";

const upscaleGrokImagineVideoSchema = {
  asset_id: z.string().optional().describe("Video artifact id"),
  video_ref: z.string().optional().describe("Video artifact id. Used as fallback when asset_id is not provided."),
  book_id: z.string().describe("Book id"),
} satisfies ZodRawShape;

type Args = SchemaArgs<typeof upscaleGrokImagineVideoSchema>;

export function upscaleGrokImagineVideoDef(engine: Engine): ToolDef {
  return {
    name: "upscale_kie_grok_imagine_video",
    description: "Upscale an existing Grok-Imagine video asset using Kie's grok-imagine/upscale. Source must have been generated by grok-imagine. Creates a new video artifact and enqueues a background job.",
    schema: upscaleGrokImagineVideoSchema,
    handler: async (args) => {
      const { asset_id: rawAssetId, video_ref, book_id } = args as Args;

      const asset_id = rawAssetId ?? (video_ref?.replace(/^@/, "") || undefined);

      if (!process.env.KIE_API_KEY) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: "KIE_API_KEY environment variable is not set" }],
        };
      }

      if (!asset_id) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: "asset_id or video_ref is required" }],
        };
      }

      const kindGate = await requireArtifactKind(engine, asset_id, ["video"], "upscale_kie_grok_imagine_video");
      if (kindGate) return kindGate;

      const manifestResult = await engine.files.manifest(asset_id);
      if (!manifestResult.ok) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: manifestResult.error.message }],
        };
      }

      const manifest = manifestResult.value;
      const videoFile = findVideoFile(manifest.files);
      if (!videoFile) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: `No video file found in asset ${asset_id}` }],
        };
      }

      const generationPayloadResult = await engine.metadata.artifacts.read<{ model?: string }>(asset_id, "generation-payload");
      if (generationPayloadResult.ok) {
        const model = generationPayloadResult.value.model;
        if (model && !model.includes("grok-imagine")) {
          return {
            isError: true as const,
            content: [{ type: "text" as const, text: `Cannot upscale ${asset_id}: source video was generated by ${model}, but upscale_grok_imagine_video only works with Grok Imagine videos.` }],
          };
        }
      }

      const kieTaskIdResult = await engine.metadata.artifacts.read<{ taskId: string }>(asset_id, "kie-task-id");
      if (!kieTaskIdResult.ok) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: `Cannot upscale ${asset_id}: no kie-task-id metadata. Source must be a Kie-generated grok-imagine video.` }],
        };
      }

      // The new artifact's label is free text derived from the source's own
      // label; the id carries no name to reuse.
      const sourceArtifact = engine.artifacts.get(asset_id);
      const baseName = (sourceArtifact.ok ? sourceArtifact.value.label?.trim() : "") || asset_id;
      const videoName = derivedLabel("upscaled", baseName);
      const assetResult = await engine.artifacts.create("vid", videoName);
      if (!assetResult.ok) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: `Failed to create video asset: ${assetResult.error.message}` }],
        };
      }

      const { artifactId: vidAssetId, path: vidAssetDir } = assetResult.value;

      const jobId = `${modelSlug("kie", "grok-imagine/upscale")}-upscale-${vidAssetId}-${Date.now()}`;

      await queue.enqueue(jobId, {
        type: "upscale_grok_imagine_video",
        sourceVideoId: asset_id,
        sourceVideoFilename: videoFile.name,
        vidAssetId,
        vidAssetDir,
        bookId: book_id,
      } as unknown as Record<string, unknown>);

      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            vid_asset_id: vidAssetId,
            source_video: asset_id,
            job_id: jobId,
            status: "enqueued",
          }),
        }],
      };
    },
  };
}
