import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import type { ClipfirstFs } from "clipfirst-fs";
import { z, type ZodRawShape } from "zod";
import { GrokImagineDurationSchema } from "@apicity/kie/zod";
import { queue } from "../queue.js";
import { writePendingTask, QUEUED_TASK_ID } from "../jobs/pending-task.js";
import { findVideoFile } from "../media-files.js";
import type { SchemaArgs, ToolDef } from "./tool-def.js";

const extendGrokImagineVideoSchema = {
  asset_id: z.string().optional().describe("Video asset ID (must be vid-*)"),
  video_slug: z.string().optional().describe("Video slug (e.g., '@vid-sunset'). Used as fallback when asset_id is not provided."),
  project_slug: z.string().describe("Project slug"),
  prompt: z.string().min(1).max(5000).describe("Describe how to extend the video"),
  extend_at: z.number().optional().describe("Seconds into the source video to start extending from (defaults to 0)"),
  extend_times: z.enum(GrokImagineDurationSchema.options).optional().describe("Extension duration in seconds: 6 or 10"),
} satisfies ZodRawShape;

type Args = SchemaArgs<typeof extendGrokImagineVideoSchema>;

export function extendGrokImagineVideoDef(fs: ClipfirstFs): ToolDef {
  return {
    name: "extend_grok_imagine_video",
    description: "Extend an existing video asset using Kie's grok-imagine/extend. Creates a new vid- asset and enqueues a background job.",
    schema: extendGrokImagineVideoSchema,
    handler: async (args) => {
      const { asset_id: rawAssetId, video_slug, project_slug, prompt, extend_at, extend_times } = args as Args;

      const asset_id = rawAssetId ?? (video_slug?.replace(/^@/, "") || undefined);

      if (!process.env.KIE_API_KEY) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: "KIE_API_KEY environment variable is not set" }],
        };
      }

      if (!asset_id) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: "asset_id or video_slug is required" }],
        };
      }

      if (!asset_id.startsWith("vid-")) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: `asset_id must start with vid-, got: ${asset_id}` }],
        };
      }

      const manifestResult = await fs.getManifest(asset_id, project_slug);
      if (!manifestResult.ok) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: manifestResult.error.message }],
        };
      }

      const manifest = manifestResult.value;
      const videoFile = findVideoFile(manifest.files);
      if (!videoFile) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: `No video file found in asset ${asset_id}` }],
        };
      }

      const generationPayloadResult = await fs.readMetadata<{ model?: string }>(asset_id, "generation-payload", project_slug);
      if (generationPayloadResult.ok) {
        const model = generationPayloadResult.value.model;
        if (model && !model.includes("grok-imagine")) {
          return {
            isError: true as const,
            content: [{ type: "text" as const, text: `Cannot extend ${asset_id}: source video was generated by ${model}, but extend_grok_imagine_video only works with Grok Imagine videos. Use extend_wan27_video or generate_wan27_i2v_video with first_clip_slug instead.` }],
          };
        }
      }

      const baseName = asset_id.startsWith("vid-") ? asset_id.slice(4) : asset_id;
      const videoName = `extend-${baseName}`;
      const assetResult = await fs.createAsset("vid", videoName, project_slug);
      if (!assetResult.ok) {
        return {
          isError: true as const,
          content: [{ type: "text" as const, text: `Failed to create video asset: ${assetResult.error.message}` }],
        };
      }

      const { assetId: vidAssetId, path: vidAssetDir } = assetResult.value;

      await writePendingTask(fs, vidAssetId, project_slug, {
        taskId: QUEUED_TASK_ID,
        taskType: "grok_imagine_extend_video",
        assetId: vidAssetId,
        assetDir: vidAssetDir,
        projectSlug: project_slug,
        createdAt: new Date().toISOString(),
        meta: {
          sourceVideoId: asset_id,
          prompt,
          ...(extend_at !== undefined ? { extend_at } : {}),
          ...(extend_times !== undefined ? { extend_times } : {}),
        },
      });

      const jobId = `grok-imagine-extend-video-${vidAssetId}-${Date.now()}`;

      await queue.enqueue(jobId, {
        type: "extend_grok_imagine_video",
        sourceVideoId: asset_id,
        sourceVideoFilename: videoFile.name,
        vidAssetId,
        vidAssetDir,
        projectSlug: project_slug,
        prompt,
        ...(extend_at !== undefined ? { extend_at } : {}),
        ...(extend_times !== undefined ? { extend_times } : {}),
      } as unknown as Record<string, unknown>);

      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            vid_asset_id: vidAssetId,
            source_video: asset_id,
            job_id: jobId,
            status: "enqueued",
          }),
        }],
      };
    },
  };
}

export function registerExtendGrokImagineVideoTool(server: McpServer, fs: ClipfirstFs): void {
  const def = extendGrokImagineVideoDef(fs);
  server.tool(def.name, def.description, def.schema, def.handler);
}
