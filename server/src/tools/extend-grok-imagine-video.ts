import { modelSlug } from "@apicity/cost";
import type { Engine } from "videobook-engine";
import { z, type ZodRawShape } from "zod";
import { GrokVideoExtendRequestSchema } from "@apicity/kie/zod";
import { queue } from "../queue.js";
import { findVideoFile } from "videobook-engine";
import type { SchemaArgs, ToolDef } from "./tool-def.js";
import { apicityField, apicityStringField } from "./schema-from-apicity.js";
import { requireArtifactKind, requireAtLeastOne, toolError } from "./_shared.js";

const grokExtend = GrokVideoExtendRequestSchema.shape.input.shape;

const extendGrokImagineVideoSchema = {
  asset_id: z.string().optional().describe("Video artifact id"),
  video_ref: z.string().optional().describe("Video artifact id. Used as fallback when asset_id is not provided."),
  book_id: z.string().describe("Book id"),
  prompt: apicityStringField(grokExtend.prompt, "Describe how to extend the video", { required: true }),
  extend_at: z.number().describe("Seconds into the source video to start extending from"),
  extend_times: apicityField(grokExtend.extend_times, "Extension duration in seconds: 6 or 10", { required: true }),
} satisfies ZodRawShape;

type Args = SchemaArgs<typeof extendGrokImagineVideoSchema>;

export function extendGrokImagineVideoDef(fs: Engine): ToolDef {
  return {
    name: "extend_kie_grok_imagine_video",
    description: "Extend an existing video asset using Kie's grok-imagine/extend. Creates a new video artifact and enqueues a background job. Requires at least one of asset_id or video_ref.",
    schema: extendGrokImagineVideoSchema,
    handler: async (args) => {
      const { asset_id: rawAssetId, video_ref, book_id, prompt, extend_at, extend_times } = args as Args;

      if (!process.env.KIE_API_KEY) {
        return toolError("KIE_API_KEY environment variable is not set");
      }

      const missingInput = requireAtLeastOne("extend_kie_grok_imagine_video", [
        { name: "asset_id", value: rawAssetId },
        { name: "video_ref", value: video_ref },
      ]);
      if (missingInput) return missingInput;

      const asset_id = rawAssetId ?? (video_ref?.replace(/^@/, "") || undefined);
      if (!asset_id) {
        return toolError("asset_id or video_ref is required");
      }

      const kindGate = await requireArtifactKind(fs, asset_id, ["video"], "extend_kie_grok_imagine_video");
      if (kindGate) return kindGate;

      const manifestResult = await fs.files.manifest(asset_id);
      if (!manifestResult.ok) {
        return toolError(manifestResult.error.message);
      }

      const manifest = manifestResult.value;
      const videoFile = findVideoFile(manifest.files);
      if (!videoFile) {
        return toolError(`No video file found in asset ${asset_id}`);
      }

      const generationPayloadResult = await fs.metadata.artifacts.read<{ model?: string }>(asset_id, "generation-payload");
      if (generationPayloadResult.ok) {
        const model = generationPayloadResult.value.model;
        if (model && !model.includes("grok-imagine")) {
          return toolError(`Cannot extend ${asset_id}: source video was generated by ${model}, but extend_kie_grok_imagine_video only works with Grok Imagine videos. Use extend_kie_wan_2_7_video or generate_kie_wan_2_7_image_to_video with first_clip_ref instead.`);
        }
      }

      // The new artifact's label is free text derived from the source's own
      // label; the id carries no name to reuse.
      const sourceArtifact = fs.artifacts.get(asset_id);
      const baseName = (sourceArtifact.ok ? sourceArtifact.value.label?.trim() : "") || asset_id;
      const videoName = `extend-${baseName}`;
      const assetResult = await fs.artifacts.create("vid", videoName);
      if (!assetResult.ok) {
        return toolError(`Failed to create video asset: ${assetResult.error.message}`);
      }

      const { artifactId: vidAssetId, path: vidAssetDir } = assetResult.value;

      const jobId = `${modelSlug("kie", "grok-imagine/extend")}-extend-${vidAssetId}-${Date.now()}`;

      await queue.enqueue(jobId, {
        type: "extend_grok_imagine_video",
        sourceVideoId: asset_id,
        sourceVideoFilename: videoFile.name,
        vidAssetId,
        vidAssetDir,
        bookId: book_id,
        prompt,
        ...(extend_at !== undefined ? { extend_at } : {}),
        ...(extend_times !== undefined ? { extend_times } : {}),
      } as unknown as Record<string, unknown>);

      return {
        content: [{
          type: "text" as const,
          text: JSON.stringify({
            vid_asset_id: vidAssetId,
            source_video: asset_id,
            job_id: jobId,
            status: "enqueued",
          }),
        }],
      };
    },
  };
}
