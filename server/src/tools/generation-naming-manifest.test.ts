describe("manifest completeness & grammar validation", () => {
  it("covers 100% of registered generation tools", () => {
    const vfs = createFs({ projectsDir: "/tmp/test-projects" });
    const tools = getAllToolDefs(vfs);
    const canonicalTools = tools.filter((t) => {
      const spec = getActionSpec(t.name);
      return spec && spec.canonical_name === t.name;
    });

    const manifestCanonicalNames = new Set(MANIFEST_ENTRIES.map((m) => m.canonical_name));
    for (const t of canonicalTools) {
      expect(manifestCanonicalNames.has(t.name)).toBe(true);
    }
    expect(canonicalTools.length).toBe(MANIFEST_ENTRIES.length);
  });

  it("ensures canonical names are unique", () => {
    const names = MANIFEST_ENTRIES.map((m) => m.canonical_name);
    const set = new Set(names);
    expect(set.size).toBe(names.length);
  });

  it("writes docs/generation-naming-manifest.md", () => {
    let md = `# Apicity 0.8 Generation Naming Manifest

This document records the authoritative mapping of existing MCP generation and support action names to canonical names aligned with installed **Apicity 0.8.0** package surfaces (@apicity/kie, fal, xai, googleflow, alibaba, cost, elevenlabs).

## Summary
- Total Actions Audited: ${MANIFEST_ENTRIES.length}
- Primary Provider Actions: ${MANIFEST_ENTRIES.filter(m => m.provider !== "workflow").length}
- Workflow / Support Actions: ${MANIFEST_ENTRIES.filter(m => m.provider === "workflow").length}

## Naming Grammar
Canonical Action Name Syntax: \`<verb>_<provider>_<model>_<operation>\`
- **Providers:** \`kie\`, \`fal\`, \`xai\`, \`google_flow\`, \`alibaba\`, \`elevenlabs\`
- **Operations:** \`text_to_image\`, \`image_to_image\`, \`edit_image\`, \`text_to_video\`, \`image_to_video\`, \`reference_to_video\`, \`edit_video\`, \`extend_video\`, \`upscale_video\`, \`motion_control\`, \`video_to_video_lip_sync\`, \`text_to_audio\`
- **No abbreviations:** \`t2i\`, \`i2v\`, \`r2v\`, \`ref\`, and \`videoedit\` are eliminated. Provider suffixes (\`_fal\`, \`_google\`) are replaced by provider-first prefixes (\`generate_fal_\`, \`generate_google_flow_\`).

## Authoritative Action Manifest

| Old MCP Action Name | Canonical Action Name | Provider | Exact Apicity 0.8 Identifier | Media | Operation | Picker Visibility | Aliases |
| --- | --- | --- | --- | --- | --- | --- | --- |
`;

    MANIFEST_ENTRIES.forEach((m) => {
      md += `| \`${m.old_name}\` | \`${m.canonical_name}\` | ${m.provider} | \`${m.apicity_identifier}\` | ${m.media_type} | ${m.operation} | ${m.picker_visibility} | \`${m.aliases.join(", ")}\` |\n`;
    });

    md += `\n## Special Case Decisions\n`;
    MANIFEST_ENTRIES.filter((m) => m.split_decision).forEach((m) => {
      md += `- **\`${m.old_name}\` -> \`${m.canonical_name}\`**: ${m.split_decision}\n`;
    });

    fs.writeFileSync("docs/generation-naming-manifest.md", md);
  });
});
