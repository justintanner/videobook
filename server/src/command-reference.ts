import type { ToolDef } from "./tools/tool-def.js";
import { buildWorkspaceActionCatalog } from "./workspace-action-catalog.js";
import { WORKSPACE_ACTION_SURFACES } from "./workspace-action-surfaces.js";
import type { WorkspaceActionCatalog } from "./workspace-action-contract.js";

function oneLine(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

function escapeTable(value: string): string {
  return oneLine(value).replaceAll("|", "\\|");
}

export function renderCommandReference(
  tools: readonly ToolDef[],
  commands: readonly Command[],
): string {
  const toolLines = [...tools]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((tool) => `- \`${tool.name}\` — ${oneLine(tool.description)}`);
  const catalog = buildWorkspaceActionCatalog(tools, commands);
  const commandLines = [...catalog.actions]
    .sort((a, b) => a.command.localeCompare(b.command))
    .map((command) => {
      const aliases = command.aliases ?? [];
      const aliasText = aliases.length > 0 ? ` (aliases: ${aliases.map((alias) => `\`${alias}\``).join(", ")})` : "";
      const target = command.handler.kind === "tool"
        ? `; MCP: \`${command.handler.tool}\``
        : command.handler.kind === "ui" ? `; UI: \`${command.handler.action}\`` : "; preview or workspace operation";
      return `- \`${command.command}\`${aliasText} — ${oneLine(command.description)}${target}`;
    });

  return `# Command Reference

Every current MCP endpoint and discoverable action is listed once. Use the Actions button on any screen, press Ctrl+Shift+K / Cmd+Shift+K, or type a slash in chat to browse the complete catalog. Search includes aliases and descriptions. A command with missing arguments opens its form; media, notebook, entity, track and clip selectors provide targets. Advanced provider alternatives retain shared input fields and show a cost review before generation.

Media commands \`/export\`, \`/delete\`, \`/reverse\` and \`/trim\` target media. Sequence operations use \`/export-sequence\`, \`/clip-delete\`, \`/clip-reverse\`, \`/clip-trim\`, and \`/clip-audio\`; clip timing uses frames and media trimming uses seconds. \`/clip-audio\` edits gain, mute, and fades on an audio-track clip. Explicit legacy clip IDs and \`/export @sequence-main\` remain accepted. Use grid addresses such as \`/crop @a1\`, \`/trim @a1 0 2\` or \`/insert @a1 0 60\`.

Image, video and audio generation runs through \`generate_image\`, \`generate_video\` and \`generate_audio\` with a model id from \`list_generation_models\`; see [generation-models.md](generation-models.md). Slash aliases match their canonical action in search. The legacy \`/skeleton\` shortcut opens a reviewed AI pose-guide request. Import owns upload transport and duplicate-byte checks; it uses a native file picker. Set \`VIDEOBOOK_DOWNLOADS_DIR\` to override the server's default Downloads directory.

Routine pointer actions return focus to chat. Editing fields, open dialogs, keyboard navigation and native playback retain focus. Closing a dialog restores its opener when appropriate; delayed work cannot take focus from a newer edit.

## MCP endpoints (${tools.length})

${toolLines.join("\n")}

## Slash actions (${catalog.actions.length}; ${commands.length} dedicated command routes)

${commandLines.join("\n")}
- \`/<project-name>\` — Switch to that project; generated dynamically for each project whose name does not conflict with a command or alias.
`;
}

export function renderWorkspaceActionCoverage(catalog: WorkspaceActionCatalog): string {
  const rows = [...catalog.actions].sort((left, right) => left.id.localeCompare(right.id)).map((action) => {
    const target = action.target.argument ? `${action.target.kind}${action.target.multiple ? " selection" : ""}: ${action.target.argument}` : action.target.kind;
    const handler = action.handler.kind === "tool" ? action.handler.tool : action.handler.kind === "ui" ? action.handler.action : action.handler.command;
    return `| \`${action.id}\` | \`${action.command}\` | ${action.aliases.join(", ")} | ${action.scope} | ${escapeTable(target)} | \`${handler}\` | ${action.surfaces.join(", ")} | ${action.focus} | ${action.confirmation} |`;
  });
  const surfaces = Object.entries(WORKSPACE_ACTION_SURFACES).map(([name, entry]) => `| ${name} | [${entry.component}](../${entry.component}) | ${entry.trigger} |`);
  const workflows = catalog.tools.filter((entry) => entry.exposure === "workflow").map((entry) => `| \`${entry.tool}\` | \`${entry.actionId}\` | ${escapeTable(entry.reason)} |`);
  return `# Workspace action coverage

Generated by \`npm run docs:commands\` from the registered tools, command definitions and surface contracts. ${catalog.tools.length} active endpoints map to ${catalog.actions.length} visible actions or their owning workflows. Unknown endpoints, handlers, aliases and missing declared surfaces fail the catalog contract.

The browser regression suite checks catalog equality, complete slash traversal, typed form discovery, named target selection, menu and slash parity, review and cancellation, real media mutations and focus. Provider generation, posting and OS clipboard integration require separate execution validation; opening a form never starts a paid job or publishes content.

## Surface entry points

| Surface | Component | Entry point |
| --- | --- | --- |
${surfaces.join("\n")}

## Actions

| Stable ID | Command | Aliases | Scope | Target | Handler | Surfaces | Focus | Review |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

## Transport and workflow ownership

| Endpoint | Visible owner | Reason |
| --- | --- | --- |
${workflows.join("\n")}
`;
}

export function renderGenerationModels(): string {
  const models = listModels({ includeHidden: true });
  const rows = models.map((model) => {
    const refs = model.slots.map((slot) => `${slot.role} ${slot.min}-${slot.max ?? "n"}`).join(", ") || "none";
    const modes = model.modes.length > 1 ? model.modes.map((mode) => mode.id).join(", ") : "";
    return `| \`${escapeTable(model.id)}\` | ${escapeTable(model.title)} | ${model.media} | ${model.entry.operations.join(", ")} | ${escapeTable(refs)} | ${modes} | ${modelIsHidden(model.entry) ? "hidden" : "visible"} |`;
  });
  const gaps = Object.entries(FRONTIER_CATALOG_GAPS).map(([endpoint, reason]) =>
    `| ${escapeTable(endpoint)} | ${escapeTable(reason)} |`).join("\n");
  const unmapped = [...new Set(Object.values(FRONTIER).flatMap((snapshot) =>
    snapshot.entries.filter((entry) => entry.endpoints.length === 0).map((entry) => entry.model)))];
  return `# Generation Models

Generated by \`npm run docs:commands\` from the media catalog (\`server/src/media/catalog.ts\`). Call \`generate_image\`, \`generate_video\` or \`generate_audio\` with one of these model ids; \`list_generation_models\` returns the same list with every option, enum, range and default read from the apicity schemas.

Image and video pickers rank exact catalog endpoints using the committed top-10 snapshots in @apicity/cost 0.17.0, originally sourced from Artificial Analysis. No leaderboard is fetched at runtime. Rankings are per operation: t2i, i2i, t2v, i2v, v2v, and r2v (derived from the text/image-to-video boards). Each ranked option shows rank, Elo, and a bundled price label; prices are indicative ranges, not a quote for the selected settings.

Configured frontier models appear first; other models retain their existing order in a separate group. Providers without credentials are marked unavailable. Saved selections and defaults stay unchanged. Catalog variants on a frontier board are included even if previously hidden; non-frontier hidden variants remain hidden. A model version or lite variant never inherits another endpoint's score.

Top-10 coverage policy: every registry endpoint must map exactly to a catalog entry or appear in the known gaps below. Models with no provider endpoint in the registry: ${unmapped.join(", ")}. Catalog gaps do not imply provider API support is missing; adding those endpoints is separate work.

| Known endpoint gap | Reason |
| --- | --- |
${gaps}

- Models: ${models.length}

| Model | Title | Media | Operations | Refs | Modes | Picker |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`;
}
