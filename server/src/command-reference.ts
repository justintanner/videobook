import type { GenerationActionSpec } from "./generation-registry.js";
import type { Command } from "./tools/video-editing-command-contract.js";
import type { ToolDef } from "./tools/tool-def.js";
import { buildWorkspaceActionCatalog } from "./workspace-action-catalog.js";
import { WORKSPACE_ACTION_SURFACES } from "./workspace-action-surfaces.js";
import type { WorkspaceActionCatalog } from "./workspace-action-contract.js";

function oneLine(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

function escapeTable(value: string): string {
  return oneLine(value).replaceAll("|", "\\|");
}

export function renderCommandReference(
  tools: readonly ToolDef[],
  commands: readonly Command[],
  actions: readonly GenerationActionSpec[],
): string {
  const historicalNames = new Map(actions.map((action) => [action.canonical_name, action.legacy_names]));
  const toolLines = [...tools]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((tool) => {
      const legacy = (historicalNames.get(tool.name) ?? []).filter((name) => name !== tool.name);
      const suffix = legacy.length > 0 ? ` (historical names, not exposed: ${legacy.map((name) => `\`${name}\``).join(", ")})` : "";
      return `- \`${tool.name}\`${suffix} — ${oneLine(tool.description)}`;
    });
  const catalog = buildWorkspaceActionCatalog(tools, commands);
  const commandLines = [...catalog.actions]
    .sort((a, b) => a.command.localeCompare(b.command))
    .map((command) => {
      const aliases = command.aliases ?? [];
      const aliasText = aliases.length > 0 ? ` (aliases: ${aliases.map((alias) => `\`${alias}\``).join(", ")})` : "";
      const target = command.handler.kind === "tool"
        ? `; MCP: \`${command.handler.tool}\``
        : command.handler.kind === "ui" ? `; UI: \`${command.handler.action}\`` : "; preview or workspace operation";
      return `- \`${command.command}\`${aliasText} — ${oneLine(command.description)}${target}`;
    });

  return `# Command Reference

Every current MCP endpoint and discoverable action is listed once. Use the Actions button on any screen, press Ctrl+Shift+K / Cmd+Shift+K, or type a slash in chat to browse the complete catalog. Search includes aliases and descriptions. A command with missing arguments opens its form; media, notebook, entity, track and clip selectors provide targets. Advanced provider alternatives retain shared input fields and show a cost review before generation.

Media commands \`/export\`, \`/delete\`, \`/reverse\` and \`/trim\` target media. Sequence operations use \`/export-sequence\`, \`/clip-delete\`, \`/clip-reverse\` and \`/clip-trim\`; clip timing uses frames and media trimming uses seconds. Explicit legacy clip IDs and \`/export @sequence-main\` remain accepted. Use grid addresses such as \`/crop @a1\`, \`/trim @a1 0 2\` or \`/insert @a1 0 60\`.

Historical MCP names remain lookup-only compatibility keys. Slash aliases match their canonical action in search. The legacy \`/skeleton\` shortcut opens a reviewed AI pose-guide request. Import owns upload transport and duplicate-byte checks; it uses a native file picker. Set \`VIDEOBOOK_DOWNLOADS_DIR\` to override the server's default Downloads directory.

Routine pointer actions return focus to chat. Editing fields, open dialogs, keyboard navigation and native playback retain focus. Closing a dialog restores its opener when appropriate; delayed work cannot take focus from a newer edit.

## MCP endpoints (${tools.length})

${toolLines.join("\n")}

## Slash actions (${catalog.actions.length}; ${commands.length} dedicated command routes)

${commandLines.join("\n")}
- \`/<project-name>\` — Switch to that project; generated dynamically for each project whose name does not conflict with a command or alias.
`;
}

export function renderWorkspaceActionCoverage(catalog: WorkspaceActionCatalog): string {
  const rows = [...catalog.actions].sort((left, right) => left.id.localeCompare(right.id)).map((action) => {
    const target = action.target.argument ? `${action.target.kind}${action.target.multiple ? " selection" : ""}: ${action.target.argument}` : action.target.kind;
    const handler = action.handler.kind === "tool" ? action.handler.tool : action.handler.kind === "ui" ? action.handler.action : action.handler.command;
    return `| \`${action.id}\` | \`${action.command}\` | ${action.aliases.join(", ")} | ${action.scope} | ${escapeTable(target)} | \`${handler}\` | ${action.surfaces.join(", ")} | ${action.focus} | ${action.confirmation} |`;
  });
  const surfaces = Object.entries(WORKSPACE_ACTION_SURFACES).map(([name, entry]) => `| ${name} | [${entry.component}](../${entry.component}) | ${entry.trigger} |`);
  const workflows = catalog.tools.filter((entry) => entry.exposure === "workflow").map((entry) => `| \`${entry.tool}\` | \`${entry.actionId}\` | ${escapeTable(entry.reason)} |`);
  return `# Workspace action coverage

Generated by \`npm run docs:commands\` from the registered tools, command definitions and surface contracts. ${catalog.tools.length} active endpoints map to ${catalog.actions.length} visible actions or their owning workflows. Unknown endpoints, handlers, aliases and missing declared surfaces fail the catalog contract. Historical generation names remain outside the active catalog.

The browser regression suite checks catalog equality, complete slash traversal, typed form discovery, named target selection, menu and slash parity, review and cancellation, real media mutations and focus. Provider generation, posting and OS clipboard integration require separate execution validation; opening a form never starts a paid job or publishes content.

## Surface entry points

| Surface | Component | Entry point |
| --- | --- | --- |
${surfaces.join("\n")}

## Actions

| Stable ID | Command | Aliases | Scope | Target | Handler | Surfaces | Focus | Review |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

## Transport and workflow ownership

| Endpoint | Visible owner | Reason |
| --- | --- | --- |
${workflows.join("\n")}
`;
}

export function renderGenerationNamingManifest(actions: readonly GenerationActionSpec[]): string {
  const providerActions = actions.filter((action) => action.provider !== "workflow").length;
  const rows = actions.map((action) => (
    `| \`${escapeTable(action.canonical_name)}\` | ${action.provider} | \`${escapeTable(action.apicity_identifier)}\` | ${action.media_type} | ${action.operation} | ${action.picker_visibility} | ${action.legacy_names.map((name) => `\`${escapeTable(name)}\``).join(", ")} |`
  ));

  return `# Generation Naming Manifest

This is the authoritative registry-derived list of canonical generation and workflow action names. Historical names resolve persisted data to canonical names but are not exposed as MCP endpoints.

## Summary

- Total actions: ${actions.length}
- Provider actions: ${providerActions}
- Workflow and support actions: ${actions.length - providerActions}

## Naming grammar

Provider-backed actions use \`<verb>_<provider>_<model>_<operation>\`. Workflow actions use concise intent-based names.

| Canonical action | Provider | Apicity or internal identifier | Media | Operation | Picker visibility | Historical names (not exposed) |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`;
}
