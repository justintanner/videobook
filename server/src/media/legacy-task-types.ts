const LEGACY_MEDIA_BY_TASK_TYPE: ReadonlyMap<string, Media> = new Map<string, Media>([
  ...LEGACY_IMAGE_TASK_TYPES.map((taskType): [string, Media] => [taskType, "image"]),
  ...LEGACY_VIDEO_TASK_TYPES.map((taskType): [string, Media] => [taskType, "video"]),
]);

export function legacyMediaForTaskType(taskType: string): Media | null {
  return LEGACY_MEDIA_BY_TASK_TYPE.get(taskType) ?? null;
}

export function legacyMediaMeta(taskType: string, meta: Record<string, unknown>): Record<string, unknown> {
  const media = legacyMediaForTaskType(taskType);
  if (!media) return meta;
  return {
    ...meta,
    media: meta.media ?? media,
    model: meta.model ?? meta.apiModel ?? meta.falEndpointId ?? taskType,
  };
}
