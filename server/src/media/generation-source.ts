import type { CostHints } from "@apicity/cost";
import type { Engine } from "videobook-engine";
import { readProviderTaskRecord } from "../provider-task-record.js";
import { MEDIA_TASK_TYPES } from "./adapters/types.js";
import { tryResolveModel } from "./descriptor.js";
import { machgenTaskUrl, machgenUpscale, machgenUpscaleRequirement, type MachGenUpscaleSpec } from "./machgen.js";
import { normalizeRefs, resolveRefInput } from "./refs.js";
import type { MediaRefs, ResolvedModel } from "./types.js";

export type GenerationSource =
  | { ok: true; refs: MediaRefs; sourceVideoIds: string[]; costHints: CostHints }
  | { ok: false; error: string };

interface MachGenOutput {
  taskId: string;
  model: unknown;
  height: unknown;
  seconds: unknown;
}

function record(value: unknown): Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value) ? value as Record<string, unknown> : {};
}

function refused(error: string): GenerationSource {
  return { ok: false, error };
}

async function sourceAssetId(engine: Engine, raw: string): Promise<string | GenerationSource> {
  try {
    return (await resolveRefInput(engine, "video", raw)).assetId;
  } catch (error) {
    return refused(`video ref ${raw}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function machgenOutput(engine: Engine, assetId: string): Promise<MachGenOutput | null> {
  const task = await readProviderTaskRecord(engine, assetId);
  if (!task || task.taskType !== MEDIA_TASK_TYPES.machgen) return null;
  const payload = await engine.metadata.artifacts.read<unknown>(assetId, "generation-payload");
  const request = payload.ok ? record(payload.value) : {};
  const config = record(request.video_config);
  return { taskId: task.taskId, model: request.model, height: config.height, seconds: config.duration_secs };
}

function sourceProblem(upscale: MachGenUpscaleSpec, output: MachGenOutput | null): string | null {
  if (!output) return "was not generated by MachGen";
  if (output.model !== upscale.sourceModel) return `is a MachGen ${String(output.model)} video`;
  if (typeof output.height !== "number" || !upscale.sourceHeights.includes(output.height)) return `is ${String(output.height)}p`;
  const seconds = output.seconds;
  if (typeof seconds !== "number" || !Number.isInteger(seconds) || seconds < upscale.minSeconds || seconds > upscale.maxSeconds) {
    return `is ${String(seconds)} s`;
  }
  return null;
}

async function resolveMachGenUpscale(engine: Engine, model: ResolvedModel, upscale: MachGenUpscaleSpec, refs: MediaRefs): Promise<GenerationSource> {
  const raws = refs.video ?? [];
  if (raws.length !== 1) return refused(`${model.title} re-renders one connected video; ${machgenUpscaleRequirement(upscale)}`);
  const raw = raws[0]!;
  if (/^https?:\/\//u.test(raw)) return refused(`${model.title} needs a video from this book, not a URL; ${machgenUpscaleRequirement(upscale)}`);
  const assetId = await sourceAssetId(engine, raw);
  if (typeof assetId !== "string") return assetId;
  const pending = engine.jobs.pending.read(assetId);
  if (pending.ok && pending.value) return refused(`${raw} is still generating; wait for it to finish`);
  const output = await machgenOutput(engine, assetId);
  const problem = sourceProblem(upscale, output);
  if (problem || !output) return refused(`${raw} ${problem ?? "was not generated by MachGen"}; ${machgenUpscaleRequirement(upscale)}`);
  const seconds = output.seconds as number;
  return {
    ok: true,
    refs: { ...refs, video: [machgenTaskUrl(output.taskId, seconds)] },
    sourceVideoIds: [assetId],
    costHints: { inputDurationSeconds: seconds, durationSeconds: seconds },
  };
}

export async function resolveGenerationSource(engine: Engine, model: ResolvedModel, refs: MediaRefs): Promise<GenerationSource> {
  const upscale = model.provider === "machgen" ? machgenUpscale(model.apiId) : null;
  if (!upscale) return { ok: true, refs, sourceVideoIds: [], costHints: {} };
  return resolveMachGenUpscale(engine, model, upscale, refs);
}

export async function sourcedGenerationInput(
  engine: Engine,
  input: Record<string, unknown>,
): Promise<{ ok: true; input: Record<string, unknown> } | { ok: false; error: string }> {
  const model = typeof input.model === "string" ? tryResolveModel(input.model.trim()) : null;
  if (!model || model.provider !== "machgen" || !machgenUpscale(model.apiId)) return { ok: true, input };
  const source = await resolveGenerationSource(engine, model, normalizeRefs(input.refs));
  return source.ok ? { ok: true, input: { ...input, refs: source.refs } } : source;
}
